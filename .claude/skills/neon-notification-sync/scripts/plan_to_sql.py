#!/usr/bin/env python3
"""Turn an approved plan into one transaction of UPDATE statements.

Usage:
    plan_to_sql.py --plan plan.json --dev dev.json --out sync.sql [--rollback]

Only keys listed in plan['push'] are emitted. Path B means editing that list by
hand first: add the conflict keys you decided in development's favour, leave out
the ones production should keep.

Safety properties, all of which matter and have all bitten before:

- Every statement targets a content row by id, never by template code.
- Bookkeeping columns are never written, so the target keeps its own history.
- jsonb payloads are dollar-quoted and cast explicitly.
- link: keys are refused. Re-wiring email_id / dashboard_alert_id is not a
  content sync and must be done deliberately.
- A row backing more than one template is annotated in the output. Two templates
  sharing a row and reconciled in opposite directions would overwrite each other.
- --rollback emits ROLLBACK instead of COMMIT, for a dry run that reports a row
  count per statement and changes nothing.
"""
import argparse
import json
import sys

TABLE = {
    'template': ('notification_templates', 'template_id'),
    'email': ('notification_template_emails', None),
    'alert': ('notification_template_dashboard_alerts', None),
    'inbox': ('notification_template_inbox_messages', None),
}
JSONB = {('notification_templates', 'recipient_params'),
         ('notification_template_emails', 'content')}
TAG = '$bulsync$'


def lit(value, table, column):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int) and (table, column) not in JSONB:
        return str(value)
    if isinstance(value, (dict, list)) or (table, column) in JSONB:
        s = json.dumps(value, ensure_ascii=False)
        cast = '::jsonb'
    else:
        s, cast = str(value), ''
    if TAG.strip('$') in s:
        sys.exit(f"refusing to emit: value for {table}.{column} contains the quote tag")
    return f"{TAG}{s}{TAG}{cast}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--plan', required=True)
    ap.add_argument('--dev', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--rollback', action='store_true')
    a = ap.parse_args()

    plan = json.load(open(a.plan))
    dev = json.load(open(a.dev))
    push = plan['push']
    if not push:
        sys.exit("plan['push'] is empty; nothing to emit")

    bad = [k for k in push if k.startswith('link:')]
    if bad:
        sys.exit(f"refusing to emit linkage changes: {bad}\n"
                 "Re-wiring email_id / dashboard_alert_id is not a content sync.")

    # group by (table, row id) so one row is written by one statement
    groups, cancels = {}, []
    for k in push:
        kind, _, rest = k.partition(':')
        if kind == 'cancellation':
            cancels.append(rest)
            continue
        if kind not in TABLE:
            sys.exit(f"unknown field kind in plan: {k}")
        ident, column = rest.rsplit(':', 1)
        table, _ = TABLE[kind]
        if kind == 'template':
            row_id = dev['display'][ident]['template_id']
            owners = [ident]
        else:
            row_id = int(ident)
            owners = dev.get('owners', {}).get(f"{kind}:{ident}", [])
        groups.setdefault((table, row_id, tuple(owners)), {})[column] = dev['fields'][k]

    out = [
        "-- Notification content sync, generated by the neon-notification-sync skill.",
        f"-- Source snapshot: {a.dev} ({dev['meta']['label']}, {dev['meta']['captured_at']})",
        f"-- Path {plan.get('path')}, {len(push)} field(s) across {len(groups)} row(s).",
        "-- Run with: psql \"$TARGET_URI\" -v ON_ERROR_STOP=1 -f " + a.out,
        "",
        "BEGIN;",
        "",
    ]
    for (table, row_id, owners), cols in sorted(groups.items(), key=lambda x: (x[0][0], x[0][1])):
        who = ', '.join(owners) if owners else 'no template references this row'
        out.append(f"-- {table} #{row_id}  [{who}]")
        if len(owners) > 1:
            out.append(f"--   ** SHARED ROW: this write changes every code listed above **")
        sets = ',\n    '.join(f"{c} = {lit(v, table, c)}" for c, v in sorted(cols.items()))
        out.append(f"UPDATE {table} SET\n    {sets}\nWHERE id = {row_id};")
        out.append("")
    for c in cancels:
        a_id, b_id = c.split('->')
        out.append(f"-- cancellation {a_id} -> {b_id}")
        out.append("INSERT INTO notification_template_cancellations "
                   "(cancelling_template_id, cancelled_template_id)\n"
                   f"VALUES ({a_id}, {b_id}) ON CONFLICT DO NOTHING;")
        out.append("")
    out.append("ROLLBACK;  -- DRY RUN" if a.rollback else "COMMIT;")

    with open(a.out, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    stmts = sum(1 for line in out if line.startswith(('UPDATE', 'INSERT')))
    print(f"{stmts} statement(s) across {len(groups)} row(s) -> {a.out}"
          f"{'  (DRY RUN, ends in ROLLBACK)' if a.rollback else ''}")
    shared = [o for (_, _, o) in groups if len(o) > 1]
    if shared:
        print(f"  ** {len(shared)} shared row(s) in this set: {shared}")


if __name__ == '__main__':
    main()
